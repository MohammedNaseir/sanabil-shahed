export function wheelStation(lab: ElementLab['id']): ElementStation {
  return {
    id: WHEEL_STATION_ID,
    n: 'عجلة الصقور 🦅',
    mode: 'المحطة الافتتاحية',
    how: 'أدِر العجلة لتتوقف عند موضوع جديد، ثم أجب عن سؤاله. الإجابة الصحيحة من المحاولة الأولى بنقطتين، وبعد محاولة خاطئة بنقطة واحدة. أجب عن الأسئلة الخمسة لتنتقل إلى التجارب.',
    kind: 'wheel',
    wheel: WHEEL[lab],
  };
}

/** يضيف «عجلة الصقور» محطةً أولى قبل محطات v5 دون تغيير ترتيبها. */
export function withWheel(labs: ElementLab[]): ElementLab[] {
  return labs.map(L => ({ ...L, stations: [wheelStation(L.id), ...L.stations] }));
}
