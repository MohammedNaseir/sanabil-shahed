const last = new Map<unknown, number>();
/** يختار عبارة عشوائية دون تكرار آخر عبارة من القائمة نفسها. */
export function pick<T>(list: readonly T[]): T {
  let i: number;
  do i = Math.floor(Math.random() * list.length);
  while (i === last.get(list) && list.length > 1);
  last.set(list, i);
  return list[i];
}

