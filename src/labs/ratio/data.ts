/** تطبيع نص عربي: حذف التشكيل والتطويل وتوحيد الألف والياء والتاء المربوطة وحذف «ال». */
export function normalizeAr(s: string) {
  return s
    .replace(/[ً-ٰٟـ]/g, '')
    .replace(/[أإآ]/g, 'ا').replace(/ى/g, 'ي').replace(/ة/g, 'ه')
    .replace(/[^ء-يa-zA-Z0-9\s]/g, ' ')
    .split(/\s+/).filter(Boolean)
    .map(w => (w.length > 3 && w.startsWith('ال') ? w.slice(2) : w))
    .join(' ');
}

export function matchesWho(text: string, item: WhoItem) {
  const n = normalizeAr(text);
  if (!n) return false;
  return item.keys.every(group => group.some(k => n.includes(normalizeAr(k))));
}

